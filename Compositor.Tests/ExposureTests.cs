    [Fact]
    public void GroupReorderDeleteUngroupAndUndoKeepAdjustmentSemantics()
    {
        var doc = Sample(); var layer = doc.Layers[1]; var group = Layer.Group("Folder", 4, 1) with { Opacity = .5 };
        doc = doc with { Layers = [doc.Layers[0], group, layer with { ParentId = group.Id }] };
        var session = new EditorSession(doc); var expected = Render(doc);
        session.Apply(d => LayerHierarchy.Ungroup(d, group.Id)); Assert.Equal(expected, Render(session.Document));
        Assert.Equal(.5, session.Document.Layers[1].Opacity); session.Undo(); Assert.Same(doc, session.Document);
        session.Apply(d => LayerHierarchy.Reorder(d, group.Id, -1)); Assert.Equal(doc.Layers[0].Pixels.ToRgba(), Render(session.Document));
