    private static Document Sample()
    {
        var doc = Document.Create(4, 1);
        var source = doc.Layers[0] with { Pixels = Raster.FromRgba(4, 1, new byte[] { 64, 128, 192, 255, 32, 64, 96, 128, 8, 16, 24, 32, 0, 0, 0, 0 }), Transform = new(0, 0, 4, 1, Sampling: Sampling.Nearest) };
