    [Theory]
    [InlineData(1f)][InlineData(1.5f)][InlineData(2f)]
    public void MultipleAdjustmentsViewportCacheAndUndoMatchCanonicalExport(float scale)
    {
        var doc = Sample(); var second = Layer.ExposureLayer(4, 1) with { Exposure = new(-.7, .02, 1.1), Opacity = .6 };
        doc = doc with { Layers = doc.Layers.Add(second) }; var session = new EditorSession(doc); using var viewport = new ViewportRenderer();
        void Compare()
        {
            using var image = viewport.Render(session.Document, 16, 8, scale, 2, 1);
            using var surface = SKSurface.Create(CanvasRenderer.Info(16, 8)); surface.Canvas.Clear(); surface.Canvas.Translate(2, 1); surface.Canvas.Scale(scale);
            using var renderer = new CanvasRenderer(); using var exported = renderer.Flatten(session.Document);
            surface.Canvas.DrawImage(exported, 0, 0, new SKSamplingOptions(SKFilterMode.Nearest)); using var expected = surface.Snapshot();
            Assert.Equal(Pixels(expected), Pixels(image));
        }
        Compare(); session.Apply(d => d.Replace(second with { Exposure = new(2, 0, .7) })); Compare();
        session.Undo(); Compare(); session.Redo(); Compare();
        session.Apply(d => d.Replace(d.Layers[0] with { Pixels = ColorAdjustments.Apply(d.Layers[0].Pixels, new(20)) })); Compare();
        session.Apply(d => d with { Layers = d.Layers.RemoveAt(1) }); Compare();
    }

    [Fact]
    public void VersionSevenAndEightRoundTripSwiftFieldsMasksAndEditableValues()
    {
        var doc = Sample(); var layer = doc.Layers[1] with { Exposure = new(1.25, -.03, 1.4), Mask = LayerMask.Solid(1, 1, 128) };
        doc = doc.Replace(layer); string path = Path.Combine(root, "Exposure.comp"); ProjectStore.Save(doc, layer.Id, path);
        string manifest = Path.Combine(path, "manifest.json"); var json = JsonNode.Parse(File.ReadAllText(manifest))!;
        var saved = json["layers"]![1]!; Assert.Null(saved["imageFile"]); Assert.NotNull(saved["maskFile"]);
        Assert.Equal("Exposure", (string)saved["adjustment"]!["kind"]!);
        Assert.Equal(4, saved["adjustment"]!["levels"]!["ranges"]!.AsArray().Count); Assert.Equal(4, saved["adjustment"]!["curves"]!["channels"]!.AsArray().Count);
        Assert.Single(Directory.GetFiles(Path.Combine(path, "images"), "*.png").Where(p => !p.EndsWith(".mask.png")));
        json["version"] = 7; File.WriteAllText(manifest, json.ToJsonString()); var loaded = ProjectStore.Load(path);
        Assert.Equal(layer.Exposure, loaded.Document.Layers[1].Exposure); Assert.Equal(Render(doc), Render(loaded.Document));
        var session = new EditorSession(loaded.Document); session.Apply(d => d.Replace(d.Layers[1] with { Exposure = new(2) })); session.Undo();
        Assert.Equal(layer.Exposure, session.ActiveLayer!.Exposure); session.Redo(); Assert.Equal(2, session.ActiveLayer!.Exposure!.Exposure);
        string png = Path.Combine(root, "Exposure.png"); ImageCodec.Export(doc, png, false); Assert.Equal(Render(doc), ImageCodec.Load(png).ToRgba());
        byte[] prior = File.ReadAllBytes(manifest); Assert.Throws<IOException>(() => ProjectStore.SaveInternal(session.Document, layer.Id, path, () => throw new IOException("injected")));
        Assert.Equal(prior, File.ReadAllBytes(manifest));
        saved["adjustment"]!["exposureSettings"] = null; File.WriteAllText(manifest, json.ToJsonString()); Assert.Equal(new(), ProjectStore.Load(path).Document.Layers[1].Exposure);
    }

    [Theory]
    [InlineData("kind")][InlineData("unknown")][InlineData("dormant")][InlineData("version")][InlineData("asset")][InlineData("group")][InlineData("gamma")][InlineData("missing")]
    public void UnsupportedOrInvalidAdjustmentsRefuseOpenAndOverwrite(string failure)
    {
        string path = Path.Combine(root, "Rejected.comp"); var doc = Sample(); ProjectStore.Save(doc, null, path);
        string manifest = Path.Combine(path, "manifest.json"); var json = JsonNode.Parse(File.ReadAllText(manifest))!; var layer = json["layers"]![1]!;
        var adjustment = layer["adjustment"]!;
        switch (failure)
        {
            case "kind": adjustment["kind"] = "Curves"; break;
            case "unknown": adjustment["exposureSettings"]!["future"] = 1; break;
            case "dormant": adjustment["hue"] = 30; break;
            case "version": json["version"] = 6; break;
            case "asset": layer["imageFile"] = "anything.png"; break;
            case "group": layer["isGroup"] = true; break;
            case "gamma": adjustment["exposureSettings"]!["gamma"] = 0; break;
            case "missing": adjustment["exposureSettings"]!.AsObject().Remove("offset"); break;
        }
        File.WriteAllText(manifest, json.ToJsonString()); byte[] prior = File.ReadAllBytes(manifest);
        if (failure is "kind" or "unknown" or "dormant")
        { Assert.Throws<NotSupportedException>(() => ProjectStore.Load(path)); Assert.Throws<NotSupportedException>(() => ProjectStore.Save(doc, null, path)); }
        else
        { Assert.Throws<InvalidDataException>(() => ProjectStore.Load(path)); Assert.Throws<InvalidDataException>(() => ProjectStore.Save(doc, null, path)); }
        Assert.Equal(prior, File.ReadAllBytes(manifest));
    }
